/**
 * Generates src/presentation/rig/rigData.ts from MPFB2's Mixamo rig.
 *
 * Source: https://github.com/makehumancommunity/mpfb2 src/mpfb/data/rigs/standard/rig.mixamo.json
 * Licence: CC0 1.0 (LICENSE.ASSETS.md in that repository). See docs/ASSETS.md.
 *
 * What it does:
 *   - orders the 52 bones parent-before-child (a stable topological order, ties
 *     broken by name, so the generated indices never depend on JSON key order);
 *   - converts Blender coordinates (Z up, character facing -Y, metres after the
 *     rig's 0.1 scale factor) to three.js coordinates (Y up, facing +Z):
 *       three = (x_b, z_b, -y_b);
 *   - keeps each bone's head/tail rest positions and the MPFB joint reference
 *     (`cube_name` / `vertex_indices`) so the character module can re-derive
 *     joints from a morphed body exactly as MakeHuman does.
 *
 *   node scripts/assets/build-rig.mjs [path/to/rig.mixamo.json]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const URL = 'https://raw.githubusercontent.com/makehumancommunity/mpfb2/master/src/mpfb/data/rigs/standard/rig.mixamo.json';
const out = resolve('src/presentation/rig/rigData.ts');

let text;
const local = process.argv[2];
if (local && existsSync(local)) text = readFileSync(local, 'utf8');
else {
  const res = await fetch(URL);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  text = await res.text();
}
const rig = JSON.parse(text);
const bones = rig.bones;

const strip = (n) => (n ? n.replace(/^mixamorig:/, '') : null);
const toThree = ([x, y, z]) => [x, z, -y].map((v) => Math.round(v * 1e5) / 1e5);

// Topological order: parents first, alphabetical among siblings.
const names = Object.keys(bones).map(strip).sort();
const parentOf = new Map(Object.entries(bones).map(([n, b]) => [strip(n), strip(b.parent)]));
const order = [];
const placed = new Set();
while (order.length < names.length) {
  const before = order.length;
  for (const n of names) {
    if (placed.has(n)) continue;
    const p = parentOf.get(n);
    if (!p || placed.has(p)) { order.push(n); placed.add(n); }
  }
  if (order.length === before) throw new Error('rig has a cycle or a missing parent');
}

const ref = (j) => (j.strategy === 'CUBE'
  ? { strategy: 'CUBE', cube: j.cube_name }
  : { strategy: j.strategy, vertices: j.vertex_indices ?? [] });

const rows = order.map((n) => {
  const b = bones[`mixamorig:${n}`];
  return {
    name: n,
    parent: parentOf.get(n) ? order.indexOf(parentOf.get(n)) : -1,
    head: toThree(b.head.default_position),
    tail: toThree(b.tail.default_position),
    headRef: ref(b.head),
    tailRef: ref(b.tail),
  };
});

const header = `/**
 * GENERATED by scripts/assets/build-rig.mjs — do not edit by hand.
 *
 * The canonical 52-bone skeleton: MPFB2's Mixamo rig (CC0 1.0,
 * github.com/makehumancommunity/mpfb2), converted to three.js coordinates
 * (Y up, character facing +Z, metres). Rest positions are MPFB's default body
 * in its T-pose. Order is parent-before-child and is part of the pose-buffer
 * contract: bone i's local rotation lives at Pose.local[4*i .. 4*i+3].
 */
`;
const body = `export interface RigBoneRow {
  name: string;
  /** Index of the parent bone, or -1 for the root (Hips). */
  parent: number;
  /** Rest head (joint) position, model space, metres. */
  head: [number, number, number];
  /** Rest tail position, model space, metres. */
  tail: [number, number, number];
  /** How MPFB locates this joint on the mesh, for re-deriving joints after morphs. */
  headRef: { strategy: string; cube?: string; vertices?: number[] };
  tailRef: { strategy: string; cube?: string; vertices?: number[] };
}

export const RIG_SOURCE = ${JSON.stringify(URL)};

export const RIG_BONES: readonly RigBoneRow[] = ${JSON.stringify(rows, null, 1)
    .replace(/\n\s+(-?[\d.]+)/g, ' $1').replace(/\n\s+\]/g, ']')};
`;
writeFileSync(out, header + body);
console.log(`wrote ${out}: ${rows.length} bones, root ${rows[0].name}`);
