function mirrorBoneName(n: string): string {
  if (n.startsWith('Left')) return 'Right' + n.slice(4);
  if (n.startsWith('Right')) return 'Left' + n.slice(5);
  return n;
}

const TABLE = new Map<string, SocketDef>();
for (const [name, [bone, t, off, n]] of Object.entries(SIDED)) {
  TABLE.set(`${name}_L`, { bone: boneIndex(bone), t, off, n: norm(n) });
  TABLE.set(`${name}_R`, {
    bone: boneIndex(mirrorBoneName(bone)), t, off: [-off[0], off[1], off[2]], n: norm([-n[0], n[1], n[2]]),
  });
}
for (const [name, [bone, t, off, n]] of Object.entries(MID)) {
  // Midline chest overrides the sided chest name only for the bare id.
  TABLE.set(name, { bone: boneIndex(bone), t, off, n: norm(n) });
}

export const SOCKET_NAMES: readonly string[] = [...TABLE.keys()];

export function hasSocket(name: string): boolean {
  return TABLE.has(name);
}

export function socketDef(name: string): SocketDef {
  const d = TABLE.get(name);
  if (!d) throw new Error(`Unknown socket: ${name}`);
  return d;
}

/** Swap the side suffix of a socket name (for mirrored poses). */
export function mirrorSocket(name: string): string {
  if (name.endsWith('_L')) return name.slice(0, -2) + '_R';
  if (name.endsWith('_R')) return name.slice(0, -2) + '_L';
  return name;
}

/** Sockets on the arms and legs move when that limb is solved. */
const LIMB_BONES = new Set<number>([
  B.lArm, B.lForeArm, B.lHand, B.rArm, B.rForeArm, B.rHand,
  B.lUpLeg, B.lLeg, B.lFoot, B.rUpLeg, B.rLeg, B.rFoot,
]);
export function isLimbSocket(name: string): boolean {
  return LIMB_BONES.has(socketDef(name).bone);
}

/** Reference stature of the default rest (crown height). */
export const REF_STATURE = 1.733;

export function restScale(rest: RestSkeleton): number {
  return rest.statureM / REF_STATURE;
}

export interface SocketSample {
  p: V3;
  n: V3;
}

/** World (or pair-space) position and normal of a socket, from an FK result. */
export function sampleSocket(name: string, world: WorldPose, rest: RestSkeleton): SocketSample {
  const d = socketDef(name);
  const s = restScale(rest);
  const i = d.bone;
  const along = lerp3([0, 0, 0], [
    rest.tail[i * 3] - rest.head[i * 3],
    rest.tail[i * 3 + 1] - rest.head[i * 3 + 1],
    rest.tail[i * 3 + 2] - rest.head[i * 3 + 2],
  ], d.t);
  const local = add(along, scale(d.off, s));
  const q = getQ(world.quat, i);
  const p = add(getV3(world.pos, i), qRot(q, local));
  return { p, n: qRot(q, d.n) };
}

/** Debug: bone name for a socket. */
export function socketBoneName(name: string): string {
  return BONES[socketDef(name).bone];
}
