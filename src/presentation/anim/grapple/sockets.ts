/**
 * CONTACT SOCKETS — named points on the body surface (docs/design/08 §5.7).
 *
 * A socket is a bone, a fraction along that bone, and an offset in the bone's
 * rest frame (identity-rest: the rest frame is model space, +Z front, +X the
 * fighter's left, Y up). Offsets are authored for MPFB's default body and are
 * scaled by the fighter's stature, so "the back of the neck" is on the back of
 * this fighter's neck whether he is 1.60 m or 2.00 m tall. Each socket also
 * carries an outward surface normal, which the hand solver uses to put the
 * palm on the surface rather than the wrist inside it.
 *
 * Sockets are written for the left side; `_R` variants are generated by
 * mirroring across X and swapping Left/Right bones.
 */
import { B, BONES, boneIndex, type RestSkeleton, type WorldPose } from '../../rig/skeleton';
import { add, getQ, getV3, lerp3, norm, qRot, scale, type V3 } from './math';

export interface SocketDef {
  bone: number;
  /** Fraction along the bone from head (0) to tail (1). */
  t: number;
  /** Offset in the bone's rest frame, metres on the reference body. */
  off: V3;
  /** Outward surface normal in the bone's rest frame. */
  n: V3;
}

type Row = [bone: string, t: number, off: V3, n: V3];

